# live watcher thread
# ---------------------------------------------------------------------------

class MangoHudWatcher:
    """Follow the MangoHud CSV in `folder` and write frametimes.csv on one clock."""

    def __init__(self, folder: str, writer: CsvWriter, offset_s: float = 0.0,
                 poll: float = 0.25, timeout: float = 600.0):
        self.folder = folder
        self.writer = writer
        self.offset_s = offset_s
        self.poll = poll
        self.timeout = timeout
        self.log_file: Optional[str] = None
        self.t0_epoch: Optional[float] = None
        self.birth_ns: Optional[int] = None
        self.n_frames = 0
        self.n_rejected = 0
        self._offset = 0
        self._header_idx = None
        self._cols = None
        self._rejected = set()
        self._stop = threading.Event()
        self._thread = None
        self.started_epoch = util.epoch()

    def start(self) -> None:
        self._thread = threading.Thread(target=self._run, name="mangohud", daemon=True)
        self._thread.start()

    def _run(self) -> None:
        deadline = time.monotonic() + self.timeout
        since_ns = util.epoch_ns()
        while not self._stop.is_set() and time.monotonic() < deadline:
            if self.log_file is None:
                p = find_log_file(self.folder, since_ns=since_ns, reject=self._rejected)
                if p:
                    self.log_file = p
                    bt = util.birthtime_ns(p)
                    self.birth_ns = bt
                    if bt is not None:
                        self.t0_epoch = bt / 1e9 + self.offset_s
                    else:
                        self.t0_epoch = os.path.getmtime(p) + self.offset_s
                    try:
                        self._header_idx, self._cols = find_header_and_cols(p)
                        with open(p, "r", errors="replace") as fh:
                            for _ in range(self._header_idx + 1):
                                fh.readline()
                            self._offset = fh.tell()
                    except (OSError, ValueError):
                        # not a usable MangoHud CSV; reject and keep looking
                        self._rejected.add(p)
                        self.log_file = None
                        self._header_idx = self._cols = None
            if self.log_file is not None and self._cols is not None:
                self._drain()
            self._stop.wait(self.poll)

    def _drain(self) -> None:
        assert self.log_file is not None
        new_offset = self._offset
        try:
            with open(self.log_file, "r", errors="replace") as fh:
                fh.seek(self._offset)
                for line in fh:
                    if not line.endswith("\n"):
                        break
                    new_offset += len(line.encode("utf-8", "replace"))
                    parts = line.rstrip("\n").split(",")
                    try:
                        ft = float(parts[self._cols["frametime"]])
                        el = int(float(parts[self._cols["elapsed"]]))
                    except (KeyError, IndexError, ValueError):
                        continue
                    if not plausible_frametime(ft):
                        self.n_rejected += 1
                        continue
                    t = (self.t0_epoch or 0.0) + el / 1e9
                    self.writer.write(t, [ft])
                    self.n_frames += 1
        except OSError:
            return
        self._offset = new_offset

    def flush(self) -> None:
        self._drain()

    def stop(self) -> None:
        self._stop.set()
        if self._thread is not None:
            self._thread.join(timeout=5)
            self._thread = None
        try:
            self._drain()
            self.writer.flush()
        except Exception:
            pass

    def info(self) -> dict:
        b = self.birth_ns
        return {
            "log_file": self.log_file,
            "birth_ns": b,
            "t0_epoch": self.t0_epoch,
            "offset_s": self.offset_s,
            "n_frames": self.n_frames,
            "n_rejected": self.n_rejected,
        }


def mapping_residuals(frames: List[Tuple[int, float]], t0: float,
                      markers: List[float]) -> List[float]:
    """Residual (ms) between each marker and the nearest mapped frame epoch.

    Used by tools/validate_mangohud_sync.py: for a SIGSTOP of known duration we
    expect the largest frametime spike's mapped epoch to land on the marker.
    """
    if not frames:
        return []
    times = [t0 + el / 1e9 for el, _ft in frames]
    out = []
    for mk in markers:
        nearest = min(times, key=lambda x: abs(x - mk))
        out.append((nearest - mk) * 1000.0)
    return out
